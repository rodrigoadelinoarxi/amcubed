/** @odoo-module **/

import { _t } from "@web/core/l10n/translation";
import OrderPaymentValidation from "@point_of_sale/app/utils/order_payment_validation";
import { AlertDialog } from "@web/core/confirmation_dialog/confirmation_dialog";
import { patch } from "@web/core/utils/patch";

// v19: payment validation moved from PaymentScreen._isOrderValid to
// OrderPaymentValidation.isOrderValid / shouldDownloadInvoice.
patch(OrderPaymentValidation.prototype, {
    //@override
    async isOrderValid(isForceValidate) {
        let res = await super.isOrderValid(...arguments);

        if (this.order.getPartner()) {
            const orderlines = this.order.getOrderlines();
            const errors = [];

            // Collect all errors
            for (const line of orderlines) {
                if (line.product_id.type == 'combo') {
                    errors.push(_t('• Combo products are not compatible with PT/AO POS Orders'));
                    break; // Only need to find one combo product
                }
            }

            for (const line of orderlines) {
                if (!line.product_id.taxes_id.length) {
                    errors.push(_t('• Some products do not have taxes configured'));
                    break; // Only need to find one line without taxes
                }
            }

            // Show single dialog with all errors
            if (errors.length > 0) {
                await this.pos.dialog.add(AlertDialog, {
                    title: _t('Order Validation Error'),
                    body: _t('Please fix the following issues:\n\n') + errors.join('\n'),
                });
                return false;
            }
        }

        return res;
    },

    shouldDownloadInvoice() {
        // Never print invoice generated by odoo. It will be printed by the fiscal printer.
        return false;
    },
});
